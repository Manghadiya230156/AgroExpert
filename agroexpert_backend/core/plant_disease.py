"""CPU inference for AgroExpert's trained MobileNetV3-Small plant classifier."""
from __future__ import annotations
import json
from functools import lru_cache
from pathlib import Path
from django.conf import settings

MODEL_DIR = Path(settings.BASE_DIR) / "core" / "ml_model"
CHECKPOINT_PATH = MODEL_DIR / "plant_disease_model.pth"
CLASS_NAMES_PATH = MODEL_DIR / "plant_disease_classes.json"
IMAGE_SIZE = 224

@lru_cache(maxsize=1)
def _load_model():
    if not CHECKPOINT_PATH.exists() or not CLASS_NAMES_PATH.exists():
        raise FileNotFoundError(
            "Plant disease model files are missing. Expected core/ml_model/plant_disease_model.pth "
            "and plant_disease_classes.json."
        )
    import torch
    from torchvision import models, transforms
    with CLASS_NAMES_PATH.open("r", encoding="utf-8") as f:
        class_names = json.load(f)
    # This is a trusted model artifact generated by the project's own training notebook.
    try:
        checkpoint = torch.load(CHECKPOINT_PATH, map_location="cpu", weights_only=True)
    except TypeError:  # compatibility with older PyTorch versions
        checkpoint = torch.load(CHECKPOINT_PATH, map_location="cpu")
    state_dict = checkpoint.get("model_state_dict", checkpoint) if isinstance(checkpoint, dict) else checkpoint
    model = models.mobilenet_v3_small(weights=None)
    model.classifier[3] = torch.nn.Linear(model.classifier[3].in_features, len(class_names))
    model.load_state_dict(state_dict)
    model.eval()
    preprocess = transforms.Compose([
        transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
        transforms.ToTensor(),
        transforms.Normalize(mean=(0.485, 0.456, 0.406), std=(0.229, 0.224, 0.225)),
    ])
    return model, class_names, preprocess, torch

def predict_plant_disease(image_file):
    """Return (class label, top-class score as percent) for a PIL image."""
    model, class_names, preprocess, torch = _load_model()
    image = image_file.convert("RGB")
    tensor = preprocess(image).unsqueeze(0)
    with torch.inference_mode():
        probabilities = torch.softmax(model(tensor), dim=1)[0]
        confidence, index = torch.max(probabilities, dim=0)
    return class_names[int(index)], float(confidence) * 100.0
